export const APP_LANGUAGES: readonly {
  value: AppLanguage;
  nativeName: string;
  shortLabel: string;
}[] = [
  { value: 'pt-BR', nativeName: 'Português (Brasil)', shortLabel: 'PT-BR' },
  { value: 'en-US', nativeName: 'English (United States)', shortLabel: 'EN-US' },
  { value: 'es-ES', nativeName: 'Español (España)', shortLabel: 'ES-ES' },
  { value: 'es-419', nativeName: 'Español (Latinoamérica)', shortLabel: 'ES-LATAM' },
];

const translations: Record<AppLanguage, Record<AppTranslationKey, string>> = {
  'pt-BR': ptBR,
  'en-US': enUS,
  'es-ES': esES,
  'es-419': es419,
};

export function translate(
  language: AppLanguage,
  key: AppTranslationKey,
  params: Readonly<Record<string, string | number>> = {},
): string {
  let value: string = translations[language][key];

  for (const [name, replacement] of Object.entries(params)) {
    value = value.split(`{${name}}`).join(String(replacement));
  }

  return value;
}

export function isAppLanguage(value: unknown): value is AppLanguage {
  return APP_LANGUAGES.some((language) => language.value === value);
}

export function detectAppLanguage(
  locales: readonly string[],
  fallback: AppLanguage = 'pt-BR',
): AppLanguage {
  for (const locale of locales) {
    const normalized = locale.trim().replace('_', '-').toLowerCase();
    const [language, region] = normalized.split('-');

    if (language === 'pt') {
      return 'pt-BR';
    }
    if (language === 'en') {
      return 'en-US';
    }
    if (language === 'es') {
      return region === 'es' ? 'es-ES' : 'es-419';
    }
  }

  return fallback;
}
